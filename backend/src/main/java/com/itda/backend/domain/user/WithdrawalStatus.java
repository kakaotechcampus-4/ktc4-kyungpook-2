package com.itda.backend.domain.user;

/**
 * 진행 중인 탈퇴의 단계 (DB 스키마 §4.1). 탈퇴가 없으면 컬럼이 비어 있다.
 *
 * <p>카카오 연결 해제는 외부 호출이라 성공 여부를 모를 수 있다. 그래서 "카카오 결과 모름" 과 "카카오 해제 확정, DB 정리만
 * 남음" 을 나눈다 — 해제가 확정된 뒤에는 카카오를 다시 부르지 않고 DB 정리만 다시 한다.
 */
public enum WithdrawalStatus {

    /** 접수했다. 카카오 연결 해제가 끝났는지 아직 모른다. */
    REQUESTED,

    /** 카카오 연결 해제가 확정됐다. 아이 연결 정리와 식별정보 삭제가 남았다. */
    KAKAO_UNLINKED
}
