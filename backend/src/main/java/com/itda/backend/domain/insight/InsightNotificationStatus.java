package com.itda.backend.domain.insight;

/**
 * 보호자 알림 한 번의 상태 (#419).
 *
 * <p>{@link InsightRunStatus} 와 같은 모양이되 {@code BLOCKED} 가 하나 더 있다. 인사이트 생성은
 * "됐다 / 안 됐다" 둘이면 되지만, 알림은 <b>재시도하면 되는 실패</b>와 <b>재시도해도 같은 실패</b>가
 * 나뉘기 때문이다 (AI/notify/CRITERIA.md §4).
 */
public enum InsightNotificationStatus {

    /** 집었고 아직 끝나지 않았다. 앱이 죽으면 이 상태로 남는다. */
    RUNNING,

    /** 나갔다. {@code message_id} 가 채워진다. */
    SENT,

    /**
     * 글은 검사를 통과했는데 <b>받을 보호자가 없었다.</b> 이메일을 아직 안 넣었거나 안 받기로 했다.
     *
     * <p><b>{@code SENT} 로 묶지 않는다.</b> 장애는 아니지만 메일도 안 나갔다. 합치면 교사 화면에
     * "보냈다" 고 뜨는데 실제로는 아무에게도 안 갔다 (#430 리뷰).
     *
     * <p>다시 집지 않는다 — 보호자가 이메일을 넣으면 그때 새 인사이트와 함께 나간다.
     */
    NO_RECIPIENT,

    /**
     * 근거 검사에 걸려 <b>보내지 않았다</b>. 교사가 봐야 한다.
     *
     * <p><b>다시 집지 않는다.</b> 재료가 그대로면 다시 써도 같은 글이 나온다 — Gate 1·Gate 2 에 반려를
     * 두지 않는 것과 같은 이유다 (§9.1). 교사가 인사이트를 고치면 새 판으로 다시 온다.
     */
    BLOCKED,

    /** 모델이나 메일 서버가 멈췄다. 다음 차례에 {@code revision + 1} 로 다시 집는다. */
    FAILED
}
