# AI/common/errors.py
"""
에이전트들이 같이 쓰는 예외.

여기 모은 이유가 있다. 매칭·검증·요약이 각자 llm.py 에 같은 이름의 예외를
두고 있었는데, main.py 가 셋을 한 모듈로 import 하면 **나중 import 가 앞을
덮어쓴다.** 그러면 @app.exception_handler 가 한쪽에만 걸리고, 다른 쪽은
핸들러 없이 500 으로 나간다. 충돌 없이 머지되고 테스트도 통과하면서
조용히 깨지는 종류다 (2026-10-05, #98 과 #101 을 합치다 실제로 겪었다).
"""


class LlmUnavailable(RuntimeError):
    """
    LLM 판단 없이는 결과를 낼 수 없을 때. main.py 가 503 으로 바꿔 응답한다.

    BE 는 5xx 면 재시도하고, 그래도 실패하면 FAILED 로 둔다. 빈 결과를 200 으로
    돌려주면 "낼 것이 없었다" 와 "모델이 죽었다" 가 구별되지 않는다.

    **상태 코드만으로는 부족하다.** 503 이 "모델이 죽었다" 인지 "이번 묶음에서
    근거를 못 댔다" 인지 BE 가 구별하지 못하면, 전자로 보고 차례를 통째로
    멈춘다. 그러면 근거가 늘 0 개인 묶음(예: "특이사항 없음" 한 줄) 하나가
    후보 맨 앞에 남아 뒤의 다른 아이들이 영영 처리되지 않는다 (#148 박찬진).

    그래서 하위 예외는 reason / message 를 덮어쓴다. 상태 코드는 503 그대로 두고
    **body 의 detail.reason 으로** 나눈다.
    """

    #: 응답 body 의 detail.reason. BE 가 이 값으로 후속 처리를 가른다.
    reason = "llm_unavailable"

    #: 응답 body 의 detail.message. **예외 메시지를 그대로 쓰지 않는다** —
    #: 거기에는 Luna 엔드포인트 주소와 아이 식별자가 들어 있다. 그쪽은 로그로만 간다.
    message = "Luna 호출 실패"
