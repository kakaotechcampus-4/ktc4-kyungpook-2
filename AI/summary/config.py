# AI/summary/config.py
"""
요약 판정에 쓰는 상수를 한 곳에 모은다.

매칭·검증과 달리 여기엔 임계값이 없다. 요약은 "무엇이다" 를 고르는 일이 아니라
글을 쓰는 일이라 점수로 가를 것이 없기 때문이다. 대신 **무엇을 버리는가**가
전부 불리언이다. 기준은 CRITERIA.md 에 있고, test_criteria_sync.py 가 둘을 묶는다.
"""

from common.luna import CHAT_PATH

# ── 근거 거르기 ─────────────────────────────────────────────────

#: 인용이 원문에 없으면 그 근거를 버린다. 모델이 조사를 바꾸거나 다듬은
#: 경우도 버린다 — 다듬은 인용은 원문이 아니다.
DROP_UNFOUND_QUOTES = True

#: 근거가 하나도 안 남은 문장은 버린다. 요약은 생성이라, 인용이 원문에
#: 있다고 해서 그 문장이 인용으로 뒷받침된다는 보장이 없다. 최소한
#: "근거가 아예 없는 문장" 만은 코드가 막는다.
DROP_CLAIMS_WITHOUT_EVIDENCE = True

#: 이름·숫자·시간·기관명이 문장에 나오면 근거 인용에도 있는지 확인한다.
#: 없으면 그 문장을 버린다. 환각이 가장 눈에 띄게 드러나는 자리다.
CHECK_PROPER_NOUNS = True

# ── 본문 조립 ───────────────────────────────────────────────────

#: 본문은 살아남은 claims 의 text 를 배열 순서대로 이어 만든다.
#: 모델에게 본문을 따로 받지 않는다 — 따로 받으면 claims 밖 문장이 생겨
#: 환각 검사가 본문을 다 덮지 못한다.
CONTENT_FROM_CLAIMS_ONLY = True

#: 반영된 일지는 살아남은 근거에서 코드가 센다. 모델에게 묻지 않는다 —
#: 모델 보고는 측정이 아니라 자기채점이다.
COVERAGE_FROM_EVIDENCE = True

# ── 말투 ────────────────────────────────────────────────────────

#: 추측은 추측으로 남긴다. "~인 듯함" 을 "~이다" 로 바꾸지 않는다.
#: 말투를 다듬다가 추측이 단정이 되는 것은 인용 대조로 잡히지 않는다 —
#: 헤지를 지워도 인용은 원문에 그대로 있기 때문이다.
KEEP_HEDGES = True

#: 감정 표현은 빼되 사실은 남긴다. "대응이 어려웠다" 는 감상이 아니라
#: 다음 돌봄에 필요한 정보다.
DROP_SENTIMENT_KEEP_FACT = True

#: 요약 대상이 아닌 사람의 이름을 쓰지 않는다. 이름 대신 관계로 적는다.
#: 요약 본문은 child_context 를 거쳐 다른 기관과 인사이트까지 간다. 검증이
#: '다수아동언급' 으로 잡지만 REVIEW 라 교사가 승인하면 통과하고, 그다음을
#: 막는 것이 없었다.
#:
#: ⚠️ 이것은 **프롬프트 규칙이다.** 지켜졌는지 코드가 보장하지 못한다.
ANONYMIZE_OTHER_NAMES = True

#: 길이를 고정하지 않는다. 기록이 한 건인 날과 세 기관에서 온 날의
#: 분량이 같을 이유가 없다.
FIXED_LENGTH = False

# ── Luna 호출 설정 ──────────────────────────────────────────────
#: 판정 기준이 아니라 접속 설정이다.

#: 접속 경로와 모델은 네 에이전트가 같이 쓴다 (common/luna.py).
#: 모델은 .env 의 LUNA_MODEL 로 바꾼다.
LUNA_CHAT_PATH = CHAT_PATH

#: 호출 제한시간만 에이전트마다 다르다.
LUNA_TIMEOUT = 90.0
