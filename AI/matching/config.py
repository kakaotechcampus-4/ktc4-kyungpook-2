"""
매칭 판정에 쓰는 상수를 한 곳에 모은다.

합류 세션에서 τ 스윕을 할 때 이 파일의 숫자만 바꾼다.
코드 여기저기에 흩어져 있으면 그때 바꿀 수가 없다.
"""

# ── status 결정 임계값 (전부 잠정. 채점 스크립트로 확정한다) ──────────

#: 이 이상이면 자동 확정
TAU_AUTO = 0.90

#: 이 미만이면 후보로 치지 않는다
TAU_REJECT = 0.60

#: 1위와 2위의 최소 격차. 이보다 좁으면 "둘 중 누군지 모르는 상태"다.
#: 0.92 대 0.91 은 확신이 높은 게 아니라 구별이 안 되는 것이다.
TAU_GAP = 0.15


# ── 이름 매칭 점수 ──────────────────────────────────────────────

#: 이름이 본문에 그대로 등장했을 때의 점수
EXACT_SCORE = 0.95

#: 퍼지로만 걸린 후보의 점수 구간. [FUZZY_MIN_RATIO, 1.0] 을 여기로 옮긴다.
#:
#: 하한이 TAU_REJECT 보다 낮은 것은 의도한 것이다. 한글 3글자 이름에서 한 글자만
#: 다른 유사도(0.667)는 이 구간에서 0.56 쯤이 되어 단독 후보가 되지 못한다.
#: "이동함" 이 '이동현' 과, "안하자" 가 '안하윤' 과 0.667 로 맞는 식의 오탐이
#: 표지 힌트(0.62)를 이겨서 오답을 만들었기 때문이다.
#: 진짜 오타는 이 점수로 걸러져도 llm_judge 가 본문을 읽고 다시 올린다.
FUZZY_SCORE_MIN = 0.50
FUZZY_SCORE_MAX = 0.88

#: 편집거리 유사도가 이 값 이상이어야 후보로 본다 (0~1)
#: 한글 3글자 이름에서 한 글자가 다르면 유사도가 정확히 0.667 이 나온다
#: ("김민준" vs "김민쥰", "김민준" vs "김서준" 둘 다 0.667).
#: 오타를 잡으려면 이 값보다 낮아야 해서 0.6 으로 둔다.
#: 세 글자 중 한 글자만 같은 경우는 0.333 이라 걸러진다.
FUZZY_MIN_RATIO = 0.6

#: 표지 힌트와 일치할 때 얹어주는 점수.
#: 힌트는 "참고용 단서"이지 정답이 아니므로 작게 준다.
HINT_BONUS = 0.03

#: 표지 힌트가 가리키는 아이가 다른 근거를 못 얻었을 때 깔아주는 바닥 점수.
#: TAU_REJECT 는 넘고 TAU_AUTO 에는 못 미치게 둬서 사람 확인으로 보낸다.
#:
#: 본문에 이름이 없을 때만이 아니라 "이 아이가 아직 점수가 없을 때" 언제나
#: 적용한다. 엉뚱한 퍼지 오탐이 하나 걸렸다는 이유로 표지 근거가 통째로
#: 사라지면 안 된다 — 놓침 21건이 전부 이 경로였다.
HINT_ONLY_SCORE = 0.62

#: 점수 상한
SCORE_CAP = 0.99

#: 본문에 이름이 그대로 없어도, 표지 힌트가 판정을 뒷받침하면 auto 를 허용할지.
#:
#: 실제 관찰일지는 표지에 이름이 있고 본문에는 없는 것이 정상이다.
#: (테스트 1,070건 중 본문에 이름이 등장하는 것은 61건뿐)
#: 이 값을 False 로 두면 나머지 전부가 review 로 가서 확인 큐가 100% 가 된다.
#: τ 스윕 때 이 플래그를 켜고/끄고 오매칭률을 비교한다.
ALLOW_AUTO_ON_HINT_ONLY = True

#: 모델과 코드가 같은 아이를 가리킬 때 둘 중 높은 점수를 쓸지.
#:
#: 두 점수는 서로 다른 것을 재고 있다. 코드 점수는 "이름·표지 근거가 얼마나
#: 강한가", 모델 confidence 는 "본문만 읽고 얼마나 특정되는가" 다.
#: 본문에 이름이 없는 기록에서 모델은 정직하게 0.55 를 주는데, 그 값으로
#: 덮으면 표지 근거(0.62)까지 같이 사라져 unmatched 로 떨어진다.
#: 명부에 없는 아이(정답이 unmatched 인 경우)와 구별이 안 되므로 max 로 합친다.
COMBINE_AGREEING_SCORES = True

#: 퍼지 매칭 결과를 이름 경계로 한 번 더 거를지.
#:
#: 한글 3글자 이름 + 100명 명부 + FUZZY_MIN_RATIO 0.6 이면 아무 문장에서나
#: 누군가 걸린다. "정교하게" 의 '정교하' 가 '정하윤' 과 0.667 로 맞는 식이다.
#: 이 오탐이 표지 힌트를 이겨서 hint_mismatch 11건이 전부 오답이었다.
#: 이름 뒤에는 조사·호칭·공백·구두점이 오지, 다른 음절이 붙지 않는다.
REQUIRE_NAME_BOUNDARY = True

#: 이름 바로 뒤에 올 수 있는 음절(조사·호칭의 첫 글자).
#: 이 목록에 없는 한글 음절이 붙어 있으면 이름이 아니라 단어 중간으로 본다.
NAME_SUFFIX_CHARS = frozenset(
    "이가은는을를와과도만의에랑께님아야씨군양한부까보처"
)

#: 성을 뗀 이름으로 부르는 경우를 별도로 인정할지.
#:
#: 교사는 "백지안이가" 보다 "지안이가" 라고 쓴다. 편집거리로는 이것이
#: 문장 조각 오탐("정교하" ↔ '정하윤', 둘 다 유사도 0.667)과 구별되지 않는다.
#: 성을 뗀 이름이 경계까지 맞게 등장하는지를 따로 보면 갈린다.
#:   백지안 → '지안'   "지안이가" 에 있음      ✓
#:   정하윤 → '하윤'   "정교하게" 에 없음      ✗
#: 같은 이름을 가진 아이가 여럿이면 전원을 후보로 남겨 multi 로 보낸다.
MATCH_GIVEN_NAME = True

#: 성을 뗀 이름으로만 걸렸을 때의 점수.
#: 전체 이름이 등장한 것이 아니므로 EXACT_SCORE 를 주지 않는다 —
#: LLM 건너뛰기 경로에 들어가지 못하고, 자동 확정에도 표지 뒷받침이 필요하다.
GIVEN_NAME_SCORE = 0.75

#: 본문에도 표지에도 근거가 글자로 없으면 unmatched 로 끊을지.
#:
#: "우리 반 막둥이가 새 신발을 자랑함" 처럼 별명·호칭만 있는 기록에서,
#: 모델은 근거가 없는데도 명부의 아무 아이를 골라 confidence 0.86 을 준다.
#: 근거가 존재하지 않으면 모델에게 묻지 않고 끊는다.
UNMATCHED_WITHOUT_ANCHOR = True

#: 자동 확정을 무엇으로 결정할지.
#:
#:   "confidence"  최고점이 TAU_AUTO 이상인지로 본다 (기존)
#:   "structural"  모델 점수를 보지 않고 불리언 조건으로만 본다
#:
#: 모델의 confidence 는 실행마다 크게 흔들린다. 같은 입력 5회에 0.72~0.98 이
#: 나오고, seed 를 넣어도 고정되지 않는다(2026-09-18 확인). 반면 "누구를
#: 골랐는가" 는 안정적이다. 흔들리는 값에 사람 확인 여부를 맡기면, 같은
#: 기록이 어제는 자동 확정되고 오늘은 확인 큐로 간다.
AUTO_GATE = "confidence"

#: 정확 일치에도 이름 경계를 요구할지.
#:
#: str.find() 만으로는 단어의 일부가 이름으로 잡힌다. 명부에 '은하' 가 있고
#: 본문이 "은하수 사진을 보며 별을 그렸다" 이면 '은하' 가 정확 일치로 걸려,
#: LLM 호출도 사람 확인도 없이 은하의 기록으로 자동 확정될 수 있다.
#: 이름 앞뒤가 모두 경계일 때만 정확 일치로 인정한다.
REQUIRE_EXACT_NAME_BOUNDARY = True

#: 경계를 못 넘은 부분 일치에 주는 점수.
#:
#: 후보로는 남기되(무시하면 진짜 이름을 놓칠 수 있다) EXACT_SCORE 아래로 둬서
#: LLM 건너뛰기 경로에 들어가지 못하게 한다. 사람 확인으로 간다.
PARTIAL_NAME_SCORE = 0.70

#: 모델이 고른 아이에게 동명이인이 있을 때 후보를 둘로 남길지.
#:
#: 이름이 같으면 본문만으로는 구별할 방법이 없다. 모델이 한 명을 골라도
#: 그것은 판단이 아니라 임의 선택이다. 생년월일 같은 구분 근거가 있을 때만
#: 한 명으로 좁히고, 없으면 둘 다 남겨 multi 로 보낸다.
SPLIT_SAME_NAME_CANDIDATES = True

#: 표지 이름이 명부에 없으면 미등록 아동으로 볼지.
#:
#: 명부에 없는 이름이 표지에 적혀 있고 본문에도 명부 아이 이름이 그대로
#: 없으면, 아직 등록되지 않은 아이의 기록이다. 이 신호를 안 쓰면 비슷한
#: 이름들이 퍼지로 걸려 multi 가 되고, 교사가 엉뚱한 선택지를 받는다.
#: (표지가 오타인 경우도 여기 걸리지만, 어차피 사람 확인 큐로 가므로
#:  multi 로 잘못된 후보를 보여주는 것보다 낫다.)
UNMATCHED_WHEN_HINT_NOT_IN_ROSTER = True


